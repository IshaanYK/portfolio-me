// Helper to reliably sanitize and encode media paths for web browsers & GitHub Pages
const BASE = import.meta.env.BASE_URL;
const sanitizePath = (pathStr) => {
    if (!pathStr) return pathStr;
    const clean = pathStr.replace(/^[/]+/, '');
    // URL-encode path segments so filenames with spaces load seamlessly on any browser or CDN
    return clean.split('/').map(segment => encodeURIComponent(segment)).join('/');
};

const resolveMedia = (arr) => arr.map(item => ({
    ...item,
    ...(item.img && {
        img: `${BASE}${sanitizePath(item.img)}`,
        rawImg: item.img
    }),
    ...(item.video && {
        video: `${BASE}${sanitizePath(item.video)}`,
        rawVideo: item.video
    })
}));

